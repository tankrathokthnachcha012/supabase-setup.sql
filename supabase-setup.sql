-- รันใน Supabase > SQL Editor ของโปรเจกต์ใหม่
create table if not exists public.students (
  id bigint generated by default as identity primary key,
  username text not null,
  first_name text not null,
  last_name text not null,
  age integer not null check (age between 1 and 100),
  department text not null,
  major text not null,
  student_id text not null unique,
  level text not null,
  motto text,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.students enable row level security;
alter table public.admin_users enable row level security;

-- ผู้เยี่ยมชมลงทะเบียนได้ แต่ไม่สามารถอ่าน/แก้ไข/ลบข้อมูล
drop policy if exists "Public can register students" on public.students;
create policy "Public can register students"
on public.students for insert to anon, authenticated
with check (true);

-- เฉพาะบัญชีที่อยู่ใน admin_users จัดการข้อมูลนักเรียนได้
drop policy if exists "Admins can read students" on public.students;
create policy "Admins can read students"
on public.students for select to authenticated
using (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "Admins can update students" on public.students;
create policy "Admins can update students"
on public.students for update to authenticated
using (exists (select 1 from public.admin_users a where a.user_id = auth.uid()))
with check (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "Admins can delete students" on public.students;
create policy "Admins can delete students"
on public.students for delete to authenticated
using (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));

-- Admin ตรวจสอบสิทธิ์ของตัวเองได้เท่านั้น
drop policy if exists "Admins can read own admin record" on public.admin_users;
create policy "Admins can read own admin record"
on public.admin_users for select to authenticated
using (user_id = auth.uid());

grant insert on public.students to anon, authenticated;
grant select, update, delete on public.students to authenticated;
grant usage, select on sequence public.students_id_seq to anon, authenticated;
grant select on public.admin_users to authenticated;
